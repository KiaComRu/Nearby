import { chromium } from 'playwright';
import { mkdtemp, rm, readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { randomBytes, createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { createApp } from '../server.mjs';
import { discoveryInterfaces } from '../lan-discovery.mjs';
import { discoveryBus } from '../test-support/discovery-bus.mjs';
const directory = await mkdtemp(path.join(tmpdir(), 'nearby-discovery-ui-'));
const applications = []; let browser;
const errors = [];
const memoryBus = process.env.NEARBY_TEST_DISCOVERY_IN_MEMORY === '1' ? discoveryBus() : null;
try {
  if (!memoryBus) assert.ok(discoveryInterfaces().length, 'A private IPv4 adapter is required to test real UDP discovery');
  for (const name of ['Первый тестовый ПК', 'Второй тестовый ПК']) applications.push(await createApp({ host: '0.0.0.0', port: 0, statistics: false, trustedLan: false, storage: path.join(directory, String(applications.length)), discovery: { name, ...(memoryBus ? { socketFactory: () => memoryBus.createSocket(), getInterfaces: () => [{ address: '127.0.0.1' }] } : {}) } }));
  const [first, second] = applications;
  browser = await chromium.launch({ headless: true });
  const [host, client] = await Promise.all([browser.newPage(), browser.newPage()]);
  for (const page of [host, client]) page.on('pageerror', error => errors.push(error.message));
  await Promise.all([host.goto(first.adminUrl), client.goto(second.adminUrl)]);
  const device = client.locator('#nearby-devices .device-card').filter({ hasText: 'Первый тестовый ПК' }).first();
  await device.getByRole('button', { name: 'Подключиться', exact: true }).waitFor({ timeout: 20000 });
  assert.equal(await device.locator('svg').count(), 1);
  assert.match(await device.locator('.device-ip').textContent(), /IP (127\.|10\.|172\.|192\.168\.)/);
  assert.equal(await client.locator('#transfer-workspace').isVisible(), false, 'Discovery is not a connection');
  await mkdir('artifacts', { recursive: true });
  await client.setViewportSize({ width: 1280, height: 900 });
  await client.screenshot({ path: 'artifacts/nearby-desktop-devices.png', fullPage: true });
  await client.setViewportSize({ width: 390, height: 844 });
  assert.ok(await client.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await client.screenshot({ path: 'artifacts/nearby-devices-mobile.png', fullPage: true });
  await client.setViewportSize({ width: 1280, height: 900 });
  assert.equal(await client.locator('#pc-connect').isVisible(), false,'Manual LAN fields are hidden in automatic mode');
  await device.getByRole('button', { name: 'Подключиться', exact: true }).click();
  assert.equal(await client.locator('#pc-connect').isVisible(), true,'A legacy discovery target opens its PIN form');
  await client.locator('#pc-diagnostic-state[data-code="ready"]').waitFor({ timeout: 12000 });
  assert.equal(await client.locator('#pc-pin').inputValue(), '', 'Discovery does not distribute the PIN');
  assert.match(await client.locator('#pc-address').inputValue(), memoryBus ? /^http:\/\/127\.0\.0\.1:/ : /^http:\/\/(10\.|172\.|192\.168\.)/);
  await client.locator('#pc-pin').fill(first.pin);
  await client.locator('#pc-connect-submit').click(); await client.waitForFunction(() => !document.querySelector('#pc-connected').hidden);
  const bytes = randomBytes(1024 * 1024 + 11);
  await client.locator('#files').setInputFiles({ name: 'discovered-peer.bin', mimeType: 'application/octet-stream', buffer: bytes });
  await client.locator('#queue .file-row').filter({ hasText: 'discovered-peer.bin' }).getByText('Получено и сохранено на компьютере', { exact: true }).waitFor({ state: 'attached' });
  const saved = (await readdir(first.inbox)).find(name => name.endsWith('-discovered-peer.bin'));
  const hash = data => createHash('sha256').update(data).digest('hex'); assert.equal(hash(await readFile(path.join(first.inbox, saved))), hash(bytes));
  await client.locator('#tab-connection').click(); await client.locator('#pc-disconnect').click(); await client.locator('#discovery').waitFor();
  await client.setViewportSize({ width: 390, height: 844 });
  await device.getByRole('button', { name: 'Подключиться', exact: true }).click();
  assert.ok(await client.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mkdir('artifacts', { recursive: true });
  await client.screenshot({ path: 'artifacts/nearby-discovery-mobile.png', fullPage: true });
  await client.setViewportSize({ width: 1280, height: 900 });
  await client.screenshot({ path: 'artifacts/nearby-discovery-desktop.png', fullPage: true });
  await first.close(); applications.shift();
  await client.locator('#pc-diagnose').click();
  await client.locator('#pc-diagnostic-state[data-code="connection-refused"]').waitFor({ timeout: 10000 });
  await client.waitForFunction(() => !document.querySelector('#nearby-devices').textContent.includes('Первый тестовый ПК'), null, { timeout: 25000 });
  assert.deepEqual(errors, []);
  await writeFile(`artifacts/Nearby-discovery-${memoryBus ? 'ci-' : ''}verification.json`, JSON.stringify({ passed: true, actualUdpMulticast: !memoryBus, twoIndependentEngines: true, selectionAndPin: true, privateAddressReachability: !memoryBus, fileBytes: bytes.length, sha256Match: true, departureAndDiagnosis: true, mobileWidth: 390, limitations: 'Two engines on one PC; physical devices and particular router/firewall still require testing', testedAt: new Date().toISOString() }, null, 2));
  console.log(`${memoryBus ? 'Simulated discovery' : 'Real UDP discovery'} UI passed: two engines, choose PC, diagnosis, PIN, 1 MiB SHA-256 transfer, departure, refusal and mobile layout.`);
} finally { await browser?.close(); await Promise.all(applications.map(app => app.close())); await rm(directory, { recursive: true, force: true }); }
